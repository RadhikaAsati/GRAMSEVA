const LanguageContext = createContext(null)

export function getSavedLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    return supportedLanguages.includes(saved) ? saved : 'en'
  } catch {
    return 'en'
  }
}

export function LanguageProvider({ children, user, token }) {
  const [language, setLanguageState] = useState(getSavedLanguage)
  const [preferenceLoaded, setPreferenceLoaded] = useState(false)

  useEffect(() => {
    let cancelled = false

    async function loadPreference() {
      if (!token) {
        setPreferenceLoaded(true)
        return
      }

      try {
        const { getLanguagePreference } = await import('../services/api.js')
        const result = await getLanguagePreference(token)
        const preferred = supportedLanguages.includes(result.preferred_language)
          ? result.preferred_language
          : 'en'

        if (!cancelled) {
          setLanguageState(preferred)
          try {
            localStorage.setItem(STORAGE_KEY, preferred)
          } catch {
            // The in-memory preference still works if storage is unavailable.
          }
        }
      } catch {
        // Keep the locally selected language if the API is temporarily unavailable.
      } finally {
        if (!cancelled) setPreferenceLoaded(true)
      }
    }

    loadPreference()
    return () => { cancelled = true }
  }, [token, user?.id])

  const changeLanguage = useCallback(async (nextLanguage) => {
    if (!supportedLanguages.includes(nextLanguage)) return

    setLanguageState(nextLanguage)
    try {
      localStorage.setItem(STORAGE_KEY, nextLanguage)
    } catch {
      // Ignore storage restrictions; current session still updates.
    }

    if (token) {
      try {
        const { saveLanguagePreference } = await import('../services/api.js')
        await saveLanguagePreference(token, nextLanguage)
      } catch {
        // Local choice remains active even if saving to the server fails.
      }
    }
  }, [token])

  const t = useCallback((key) => {
    return translations[language]?.[key] ?? translations.en[key] ?? key
  }, [language])

  const value = useMemo(() => ({
    language,
    setLanguage: changeLanguage,
    t,
    preferenceLoaded,
  }), [language, changeLanguage, t, preferenceLoaded])

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error('useLanguage must be used inside LanguageProvider')
  }
  return context
}
